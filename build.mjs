// DSHBuddy build script.
//   host:   src/host/index.ts    -> lib/index.js    (ESM, Node)
//   client: src/client/index.tsx -> lib/client.js   (window.__ModuleLoader__.load CJS bundle)
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL(".", import.meta.url));

// Single source of truth for the version: package.json → __DSHBUDDY_VERSION__
// inlined into both bundles (AboutTab displays it; no more hardcoded strings).
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const VERSION_DEFINE = { __DSHBUDDY_VERSION__: JSON.stringify(version) };
const development = process.argv.includes("--development");
if (!development) rmSync(join(root, "lib", "index.js.map"), { force: true });

// Generate the declaration tree advertised by package.json. esbuild strips
// types, so publishing without this separate pass produced broken `types`
// export targets.
const typesDir = join(root, "lib", "types");
rmSync(typesDir, { recursive: true, force: true });
mkdirSync(typesDir, { recursive: true });
execFileSync(
  process.execPath,
  [
    join(root, "node_modules", "typescript", "bin", "tsc"),
    "--project", join(root, "tsconfig.json"),
    "--declaration", "--emitDeclarationOnly", "--noEmit", "false",
    "--outDir", typesDir,
  ],
  { stdio: "inherit" },
);

function indent(text, spaces) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length ? pad + line : line))
    .join("\n");
}

// Host half: plain Node ESM. Cordis + @deepseek-ai packages stay external
// (they resolve from the dsh profile's node_modules at runtime).
await build({
  entryPoints: [join(root, "src/host/index.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outfile: join(root, "lib/index.js"),
  external: ["@deepseek-ai/*"],
  define: VERSION_DEFINE,
  sourcemap: development,
  minify: !development,
  legalComments: "none",
  logLevel: "info",
});

// Client half: CJS bundle wrapped in the ModuleLoader registration that the
// dsh web shell expects. React / cordis / @deepseek-ai client packages resolve
// from the shell's module graph (they are not bundled).
const clientResult = await build({
  entryPoints: [join(root, "src/client/index.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  write: false,
  external: [
    "react",
    "react/jsx-runtime",
    "@deepseek-ai/*",
  ],
  define: VERSION_DEFINE,
  sourcemap: development ? "inline" : false,
  minify: !development,
  legalComments: "none",
  logLevel: "info",
});

const code = clientResult.outputFiles[0].text;
const wrapped = `// DSHBuddy client bundle (generated by build.mjs — do not edit)\nwindow.__ModuleLoader__.load({\n\tid: "dshbuddy",\n\tfactory: (require) => {\n\t\tvar module = { exports: {} };\n\t\tvar exports = module.exports;\n${indent(code, 2)}\n\t\treturn module.exports;\n\t}\n});\n`;
writeFileSync(join(root, "lib/client.js"), wrapped);

console.log("DSHBuddy build complete: bundles + lib/types declarations");

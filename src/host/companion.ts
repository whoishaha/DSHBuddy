/**
 * CompanionEngine — proactive caring (主动关心).
 *
 * The pet proactively pops a caring bubble based on the user's REAL usage
 * records (turns / tools / errors / intensity / level / career / streak /
 * chronotype) and their CURRENT state (mood / energy / time of day / idle vs
 * busy), rather than firing on a fixed schedule.
 *
 * Triggers:
 *   greeting        first activity of a new day — time-aware, festival-aware
 *   welcome-back    user returns after a long idle gap
 *   rest-reminder   continuous active time exceeds the configured threshold
 *   micro-care      rotating 水/眼/伸展 nudges during long active stretches
 *   lunch           lunchtime nudge on active days
 *   late-night      working deep into the night → sleep care
 *   reach-out       user silent for a long while → friendly conversation starter
 *   energy-nudge    low energy + rough day → comfort & encouragement
 *   day-summary     evening recap of the day's work
 *   milestone       level-up / title / career / growth milestones
 *
 * Every message is generated by the LLM from the usage snapshot + the trigger
 * context (with a deterministic template fallback when the LLM is off), and is
 * rate-limited per trigger so the pet stays "克制、低频、不打扰". Quiet hours
 * (01:00–07:00) suppress everything except the late-night care itself.
 *
 * v0.4 timing intelligence (companion-v2 batch A):
 *   flow guard       a ≥25min continuous agent run suppresses interrupt-y cares;
 *                    when the flow ends the pet congratulates instead of nagging
 *   natural break    returning after ≥10min away defers rest/micro nudges 45min
 *                    (the user JUST rested — reminding them again is nagging)
 *   escalation       gentle kinds ride the bubble channel first; a repeat of
 *                    the same kind within 90min upgrades to the 鲸灵 card
 *   rhythm targeting social openers only fire in the user's LOW-activity hours,
 *                    never during their peak hours (hourActivity heatmap)
 */


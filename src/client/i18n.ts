const dicts: Record<string, Record<TKey, string>> = { zh, en };
let lang = "zh";

export function setLang(l: string) {
  if (l in dicts) lang = l;
}

export function currentLang(): string {
  return lang;
}

/** Translate; {0} {1}… placeholders are filled from `params` in order. */
export function t(key: TKey, params?: (string | number)[]): string {
  let s = (dicts[lang] ?? zh)[key] ?? zh[key];
  if (params) {
    params.forEach((p, i) => {
      s = s.replace(`{${i}}`, String(p));
    });
  }
  return s;
}
